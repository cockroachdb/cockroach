// ID represents an identifier that is guaranteed to be unique across
// a cluster. It is a wrapper around a uint128. It logically consists of 96 bits
// of HLC timestamp, and 32 bits of node ID.
type ID struct {
	uint128.Uint128
}

var _ redact.SafeValue = ID{}

// SafeValue implements the redact.SafeValue interface.
func (ID) SafeValue() {}

// GenerateID takes a timestamp and SQLInstanceID, and generates a
// ID.
func GenerateID(timestamp hlc.Timestamp, instID base.SQLInstanceID) ID {
	loInt := (uint64)(instID)
	loInt = loInt | ((uint64)(timestamp.Logical) << 32)

	return ID{Uint128: uint128.FromInts((uint64)(timestamp.WallTime), loInt)}
}

// IDFromString converts a string to a ID. If the string is
// not a valid uint128, an error is returned.
func IDFromString(s string) (ID, error) {
	id, err := uint128.FromString(s)
	if err != nil {
		return ID{}, err
	}
	return ID{Uint128: id}, nil
}

// IDFromBytes converts raw bytes into a ID.
// The caller is responsible for ensuring the byte slice contains 16 bytes.
func IDFromBytes(b []byte) ID {
	id := uint128.FromBytes(b)
	return ID{Uint128: id}
}

// GetNodeID extracts the node ID from a ID.
func (id ID) GetNodeID() int32 {
	return int32(0xFFFFFFFF & id.Lo)
}

// ShortID computes a probabilistically unique 64-bit identifier for
// the ID. It is used as a compact wire representation in places where
// the full 128-bit ID would inflate per-request overhead and a
// vanishingly small collision rate is acceptable (notably ASH sample
// enrichment, where a collision causes attribution noise but never
// corruption).
//
// The mixing function is MurmurHash3's fmix64 finalizer applied to a
// hash-combine of (Hi, Lo). Both halves of the ID carry useful
// entropy (Hi is the HLC walltime, Lo packs the HLC logical counter
// and the SQL instance ID), and mixing them defends against the
// otherwise-likely cross-node collisions you would get if you simply
// truncated either half.
//
// Note that ShortID of the zero ID is zero — fmix64 is a bijection
// and maps 0 to 0, so ShortID({0,0}) == 0. Callers that use 0 as an
// "unset" sentinel (such as kvpb.Header.EnrichmentID) rely on this
// being unreachable for real inputs, which it is: clusterunique.IDs
// generated by GenerateID set Hi from hlc.Timestamp.WallTime, which
// is nonzero in any running cluster (HLC walltime monotonically
// increases from process startup).
//
// Collision analysis assumes uniformly random outputs (the mixing
// function approximates this for the realistic input distribution).
// Because the enrichment cache evicts FIFO at a configurable
// capacity W (default 65,536), only in-window collisions can cause
// cross-attribution: a stale ID that's been evicted can't collide
// with a fresh insert. The per-insert in-window collision
// probability is W/2^64 ≈ 2^-48 at the default capacity, giving an
// expected total of ≈ 3.5·10^-4 cross-attributions over 10^11
// lifetime queries. Acceptable for an observability feature.
//
// ShortID is intentionally allocation-free and inlinable; it
// compiles to a handful of multiplications and XORs.
func (id ID) ShortID() uint64 {
	return fmix64(id.Hi ^ fmix64(id.Lo))
}

// fmix64 is MurmurHash3's 64-bit finalizer. It avalanches its input
// such that each bit of the input affects each bit of the output
// with approximately 50% probability. See
// https://github.com/aappleby/smhasher/blob/master/src/MurmurHash3.cpp.
func fmix64(k uint64) uint64 {
	k ^= k >> 33
	k *= 0xff51afd7ed558ccd
	k ^= k >> 33
	k *= 0xc4ceb9fe1a85ec53
	k ^= k >> 33
	return k
}

// Size returns the marshalled size of id in bytes.
func (id ID) Size() int {
	return len(id.GetBytes())
}

// MarshalTo marshals id to data.
func (id ID) MarshalTo(data []byte) (int, error) {
	return copy(data, id.GetBytes()), nil
}

// Unmarshal unmarshals data to id.
func (id *ID) Unmarshal(data []byte) error {
	if len(data) != 16 {
		return errors.Errorf("input data %s for uint128 must be 16 bytes", data)
	}
	id.Uint128 = uint128.FromBytes(data)
	return nil
}

// MarshalJSON returns the JSON encoding of u.
func (id ID) MarshalJSON() ([]byte, error) {
	return json.Marshal(id.String())
}

// UnmarshalJSON unmarshal the JSON encoded data into u.
func (id *ID) UnmarshalJSON(data []byte) error {
	var uint128String string
	if err := json.Unmarshal(data, &uint128String); err != nil {
		return err
	}

	uint128, err := uint128.FromString(uint128String)
	if err != nil {
		return err
	}

	id.Uint128 = uint128
	return nil
}

// ID implements llrb.Comparable.
// While these IDs don't really have a global ordering, it is convenient to
// be able to use them as keys in our `cache.OrderedCache`: their ordering
// is at least monotonically increasing within the same SQL instance, and
// that can be useful.
var _ llrb.Comparable = ID{}

// Compare returns a value indicating the sort order relationship between the
// receiver and the parameter.
func (id ID) Compare(o llrb.Comparable) int {
	return id.Uint128.Compare(o.(ID).Uint128)
}
